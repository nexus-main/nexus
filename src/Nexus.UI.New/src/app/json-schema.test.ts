describe('server-generated configuration contracts', () => {
  it('accepts generated CLR formats without changing local times or decimal values', () => {
    const schema = serverSchemas['formats']
    const value = { id: '04cbf330-2337-4361-90db-3798a4b654cb', count: 12, amount: 0.3,
      time: '12:34:56.1234567', timestamp: '2026-09-16T12:34:56.1234567' }
    const before = JSON.stringify(value)
    assert.equal(validateConfiguration(schema, {}).valid, true)
    assert.equal(validateConfiguration(schema, value).valid, true)
    assert.equal(JSON.stringify(value), before)
    assert.equal(validateConfiguration(schema, { ...value, count: -1 }).valid, false)
    assert.equal(validateConfiguration(schema, { ...value, id: 'invalid' }).valid, false)
    assert.equal(validateConfiguration(schema, { ...value, time: '25:34:56' }).valid, false)
  })

  it('accepts combined flags and enforces generated byte bounds including nullable roots', () => {
    const schema = serverSchemas['flagsAndByte']
    assert.equal(validateConfiguration(schema, { flags: 3, nullableFlags: null, value: 255, nullableValue: null }).valid, true)
    for (const value of [-1, 256, 1.5]) {
      assert.equal(validateConfiguration(schema, { value }).valid, false)
      assert.equal(validateConfiguration(schema, { flags: value }).valid, false)
    }
    const root = serverSchemas['nullableFlagsRoot']
    assert.equal(validateConfiguration(root, null).valid, true)
    assert.equal(validateConfiguration(root, 3).valid, true)
    assert.equal(validateConfiguration(root, 256).valid, false)
    assert.equal(getSchemaView(root).kind, 'integer')
    assert.equal(getSchemaView(root).nullable, true)
  })

  it('preserves required presence and nullable roots from the actual descriptions generator', () => {
    const schema = serverSchemas['nonNullableRoot']
    assert.equal(validateConfiguration(schema, null).valid, false)
    assert.equal(validateConfiguration(schema, {}).valid, false)
    assert.equal(validateConfiguration(schema, { requiredNullable: null }).valid, true)
    assert.equal(validateConfiguration(schema, { requiredNullable: null, optionalNonNullable: null }).valid, false)
    const nullable = serverSchemas['nullableRoot']
    assert.equal(validateConfiguration(nullable, null).valid, true)
    assert.equal(validateConfiguration(nullable, {}).valid, false)
    assert.equal(validateConfiguration(nullable, { requiredNullable: 'value' }).valid, true)
    assert.equal(getSchemaView(nullable).nullable, true)
    assert.equal(getSchemaView(nullable).kind, 'object')
  })

  it('renders and validates generated reference, dictionary, and nullable value roots', () => {
    const reference = serverSchemas['nullableReference']
    assert.equal(validateConfiguration(reference, { child: null }).valid, true)
    assert.equal(validateConfiguration(reference, { child: {} }).valid, false)
    assert.equal(validateConfiguration(reference, { child: { name: 'child' } }).valid, true)
    assert.equal(getSchemaView(reference, ['#/properties/child']).nullable, true)
    const dictionary = serverSchemas['dictionaryRoot']
    assert.equal(validateConfiguration(dictionary, { first: { name: 'child' } }).valid, true)
    assert.equal(validateConfiguration(dictionary, { first: null }).valid, false)
    assert.equal(getSchemaView(dictionary).allowAdditional, true)
    const value = serverSchemas['nullableValueRoot']
    assert.equal(validateConfiguration(value, null).valid, true)
    assert.equal(validateConfiguration(value, 12).valid, true)
    assert.equal(validateConfiguration(value, 1.5).valid, false)
    assert.equal(getSchemaView(value).nullable, true)
  })
})
